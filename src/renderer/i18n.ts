export const translations: Record<'tr' | 'en', Record<LangKey, string>> = { tr, en };

let currentLang: 'tr' | 'en' = 'tr';

export function setLanguage(lang: 'tr' | 'en') {
  currentLang = lang;
}

export function getLanguage(): 'tr' | 'en' {
  return currentLang;
}

export function t(key: LangKey, vars?: Record<string, string | number>): string {
  let s = translations[currentLang][key] ?? translations.tr[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** Applies translations to all elements with data-i18n / data-i18n-title / data-i18n-placeholder. */
export function applyTranslations(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as LangKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle as LangKey);
  });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder as LangKey);
  });
  document.documentElement.lang = currentLang;
}
